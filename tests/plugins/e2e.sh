# --- the recording relay -----------------------------------------------------------------------------
# relay.py <log> <portfile> (--upstream URL [--lose N] | --answer-self): every request's path and body
# is appended to <log> BEFORE anything is answered — so what the agent SENT is measured before the
# pod's re-check could refuse it.
cat >"$work/relay.py" <<'PY'
import base64, http.server, json, sys, urllib.error, urllib.request
log, portfile, mode = sys.argv[1], sys.argv[2], sys.argv[3]
upstream = sys.argv[4] if mode == "--upstream" else None
lose = int(sys.argv[6]) if len(sys.argv) > 6 and sys.argv[5] == "--lose" else 0
count = 0
class H(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def reply(self, status, body):
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def do_POST(self):
        global count
        body = self.rfile.read(int(self.headers.get("Content-Length", "0")))
        count += 1
        with open(log, "a") as f:
            f.write(json.dumps({"n": count, "path": self.path, "body": base64.b64encode(body).decode()}) + "\n")
        if upstream is None:
            d = json.loads(body)
            fr = d.get("frames")
            if fr and fr["index"] < fr["count"] - 1:
                return self.reply(202, json.dumps({"frame": fr["index"], "of": fr["count"]}).encode())
            return self.reply(200, json.dumps({"stored_to": d["to"], "seq_to": 1}).encode())
        req = urllib.request.Request(upstream + self.path, data=body, method="POST",
            headers={k: v for k, v in self.headers.items() if k.lower() in ("authorization", "content-type")})
        try:
            with urllib.request.urlopen(req) as r:
                status, answer = r.status, r.read()
        except urllib.error.HTTPError as e:
            status, answer = e.code, e.read()
        if count == lose:
            return self.reply(502, b"lost\n")
        self.reply(status, answer)
srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), H)
with open(portfile + ".tmp", "w") as f:
    f.write(str(srv.server_address[1]))
import os; os.rename(portfile + ".tmp", portfile)
srv.serve_forever()
PY
relay=""
relay_url=""
start_relay() { # start_relay <name> <args…> → $relay, $relay_url
