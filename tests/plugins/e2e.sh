if [[ "${1:-}" == "--self-test" ]]; then
  command -v git >/dev/null 2>&1 || couldnt "\`git\` is not on PATH — the self-test copies the tracked tree with it"
  work="$(mktemp -d "${TMPDIR:-/tmp}/cairn-plugins-e2e-selftest-XXXXXX")"
  trap 'rm -rf "$work"' EXIT
  sabotaged=0
  caught=0
  missed=()
  # sabotage <name> <file> <exact text, may span lines> <replacement> <assertion that must FAIL>
  sabotage() {
    local name="$1" file="$2" anchor="$3" replacement="$4" must_fail="$5"
    local tree="$work/$name"
    mkdir -p "$tree"
    # Tracked AND new-untracked files, so an uncommitted change under test is in the copy; no `.git`
    # is copied, so nothing in the copy can reach the real repository.
    (cd "$src" && git ls-files -z -co --exclude-standard | xargs -0 cp --parents -t "$tree" 2>/dev/null)
    python3 - "$tree/$file" "$anchor" "$replacement" "$name" <<'PY' || exit 2
import sys
path, anchor, replacement, name = sys.argv[1:5]
text = open(path, encoding="utf-8").read()
n = text.count(anchor)
if n != 1:
    sys.stderr.write(f"HARNESS ERROR: sabotage {name}: the anchor occurs {n} times in {path} (need exactly 1)\n")
    sys.exit(2)
open(path, "w", encoding="utf-8").write(text.replace(anchor, replacement))
PY
    if cmp -s "$src/$file" "$tree/$file"; then
      echo "HARNESS ERROR: sabotage $name: the copy of $file is unchanged after the edit" >&2
      exit 2
    fi
    sabotaged=$((sabotaged + 1))
    local out rc
    out="$(E2E_SOURCE="$tree" "$repo/tests/plugins/e2e.sh" 2>&1)"
    rc=$?
    if [[ $rc -eq 2 ]]; then
      echo "$out" | tail -20
      echo "HARNESS ERROR: sabotage $name: the sabotaged run could not vouch (exit 2)" >&2
      exit 2
    fi
    if [[ $rc -eq 1 ]] && grep -qxF "FAIL $must_fail" <<<"$out"; then
      caught=$((caught + 1))
      echo "CAUGHT $name: exit $rc, and FAIL $must_fail ($(grep -c '^FAIL ' <<<"$out") assertion(s) red)"
    else
      missed+=("$name")
      echo "MISSED $name: exit $rc; 'FAIL $must_fail' $(grep -qxF "FAIL $must_fail" <<<"$out" && echo present || echo ABSENT)"
    fi
  }
  # (a) No compare-and-swap on a stream: any `from` is accepted, so a stale one is stored (and a
  #     resumed run appends its records a second time).
  sabotage a-cas-accepts-any-from internal/transcript/archive/archive.go \
    $'\tif u.From != pos.StoredTo {\n\t\ta.dropFrames(u.Root, "stream:"+stream)' \
    $'\tif false {\n\t\ta.dropFrames(u.Root, "stream:"+stream)' \
    "a-stale-from-409-names-stored-position"
  # (a, the opencode leg) The plan saved before a write is never matched against the position the
  #     pod holds, so a stream whose sent units opencode then mutated cannot be resumed.
  sabotage a-opencode-plan-never-matched internal/capture/state.go \
    $'\t\tif u.End != storedTo {' \
    $'\t\tif u.End != storedTo || true {' \
    "a-opencode-resume-after-sent-units-changed"
  # (b) The agent skips redaction for persisted tool_result content (the blob path). The pod's
  #     re-check then refuses the blob and the agent stores a placeholder — but the relay already
  #     saw the secret leave, which is what (b) measures.
  sabotage b-tool-result-blob-unredacted internal/capture/agent.go \
    $'\tout, _ := a.Redactor.Blob(name, data)' \
    $'\tout := data' \
    "b-no-planted-secret-leaves-the-host"
  # (c) The pod-side scan of a record dropped.
  sabotage c-pod-recheck-dropped internal/transcript/archive/archive.go \
    $'\t\tif _, hits := a.cfg.Recheck.Record(c.Bytes()); len(hits) > 0 {' \
    $'\t\tif false {' \
    "c-dirty-record-422-nothing-stored"
  # (d) The transcript rendered without asking the predicate: a stranger's session page is then
  #     FOUND by the transcript and shows it, and the raw-record row serves it.
  sabotage d-rendered-without-the-predicate internal/transcript/visible.go \
    $'\tif !Visible(viewer, meta, v) {\n\t\treturn nil, nil\n\t}\n\treturn &View{' \
    $'\tif false {\n\t\treturn nil, nil\n\t}\n\treturn &View{' \
    "d-owner-sees-it-and-a-stranger-gets-the-no-transcript-bytes"
  # (e) Decision 3's trap: the written set computed over the VIEWER's readable scopes instead of
  #     the whole store, so every scope found is readable and the reader of one written scope sees it.
  sabotage e-written-set-over-the-viewers-scopes internal/transcript/visible.go \
    $'written, err := WrittenScopes(s.storeRoot, ids)' \
    $'written, err := writtenWithin(s.storeRoot, viewer.Auth.VisibleScopes(control.VerbRead), ids)' \
    "e-a-reader-of-one-written-scope-gets-the-no-transcript-bytes"
  # (f) The read half dropped from V: what the pod derived and what the agent declared are ignored.
  sabotage f-read-half-dropped-from-v internal/transcript/visible.go \
    $'out := slices.Concat(written.Scopes, written.Unscanned, meta.Derived, meta.Declared)' \
    $'out := slices.Concat(written.Scopes, written.Unscanned)' \
    "f-a-reader-of-the-written-scope-alone-gets-the-no-transcript-bytes"
  # (g) "Every scope of the empty set" treated as true.
  sabotage g-empty-set-vacuously-readable internal/transcript/visible.go \
    $'\tif len(v) == 0 {\n\t\treturn false\n\t}\n\treturn viewer.readsEvery(v)' \
    $'\treturn viewer.readsEvery(v)' \
    "g-a-session-with-no-write-or-read-is-owner-only"
  # (h) Routing on the first scope only — the WRITTEN `alpha-notes` sorts first — so the read of
  #     `beta-notes` no longer holds the session.
  sabotage h-routes-on-one-scope internal/capture/route.go \
    $'\tfor _, scope := range v {' \
    $'\tfor _, scope := range v[:1] {' \
    "h-held-session-reaches-neither-instance"
  echo "SUMMARY e2e-self-test: sabotaged=$sabotaged caught=$caught"
  if [[ ${#missed[@]} -gt 0 ]]; then
    echo "a sabotage that leaves its clause green is a clause that cannot fail: ${missed[*]}" >&2
    exit 2
  fi
  [[ $sabotaged -gt 0 && $caught -eq $sabotaged ]] && exit 0
  exit 2
fi

