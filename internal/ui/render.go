// the project or the role, and it cannot say that a link is dead. It can only say what will
// happen if it is live.
//
// ⚠ THE ONE DISTINCTION IT DOES DRAW IS "the URL carried no token at all", WHICH IS NOT AN
// ORACLE. That is a fact about the caller's own address bar — a truncated paste, a link
// somebody retyped — and no token was presented for the answer to be about. Rendering the
// accept form anyway would post an empty invitation and complete as an ordinary sign-in,
// which for somebody who was invited is the most confusing possible outcome: they would end
// up signed in, or refused, with no sign that the link was the problem.
func JoinPage(token string, provider bool) g.Node {
	return c.HTML5(c.HTML5Props{
		Title:    "cairn — accept an invitation",
		Language: "en",
		Head:     []g.Node{stylesheetLink()},
		Body: []g.Node{
			h.Header(h.Class("page-header"), h.H1(g.Text("cairn"))),
			h.Main(
				h.Class("join-main"),
				h.H2(g.Text("You have been invited")),
				g.If(token == "", h.P(h.Class("refused"), g.Text(
					"This link carries no invitation. Ask whoever sent it for the whole "+
						"link — it may have been cut short on the way."))),
				g.If(token != "" && !provider, h.P(h.Class("refused"), g.Text(
					"This deployment cannot accept an invitation right now: signing in with "+
						GitHubLabel+" is unavailable, and that is the only way to redeem one."))),
				g.If(token != "" && provider, h.P(h.Class("note"), g.Text(
					"Signing in with "+GitHubLabel+" accepts the invitation and creates your "+
						"account here if you do not have one. Nothing is recorded until you do."))),
				g.If(token != "" && provider, joinForm(token)),
			),
		},
	})
}

// joinForm is the accept button: a POST that starts the provider flight carrying the token.
//
// 🔴 IT IS THE SAME ROW `providerForm` POSTS TO, WITH ONE EXTRA FIELD, AND NOT A SECOND
// SIGN-IN PATH. `POST /sign-in/github` is where a flight is opened, and the invitation rides
// on that SERVER-SIDE flight record rather than on a cookie or on the provider redirect's
// query string — the operator decision and its two rejected alternatives are recorded at
// `flight.invite`. A second route here would be a second place the flight is opened, and the
// copy that forgot the per-client bound would be the one on the newer door.
//
// 🔴 A FORM AND NOT A LINK, FOR `providerForm`'s REASON: `stateChanging` calls `GET` safe, so
// a link would be reachable by any `<img src>` in the world and by every link prefetcher,
// each of which would mint a flight and overwrite the visitor's flight cookie. Here that
// would also SPEND the invitation's one flight slot before the person clicked anything.
//
// ⚠ NO CSRF TOKEN, AND ITS ABSENCE IS A CONSEQUENCE RATHER THAN AN OVERSIGHT — there is no
// session yet, so there is nothing to derive one from. Gate (2), the same-origin check, is
// what stands in front of this row, and it runs on every state-changing request before
// authentication for exactly this case.
func joinForm(token string) g.Node {
	return h.FormEl(
		h.Class("signin-provider"),
		h.Method("post"),
		h.Action(OAuthStartPath),
		// The visitor's own token, going back into the request that spends it, in a quoted
		// attribute value gomponents escapes. See `handleJoinPage` for why this is not the
		// reflected-sentence shape `outcomeFrom` refuses.
		h.Input(h.Type("hidden"), h.Name(inviteTokenField), h.Value(token)),
		h.Button(h.Type("submit"), g.Text("Accept with "+GitHubLabel)),
	)
}

// taskItem is the one href position that carries USER TEXT, and the only place
// [safeHref] is reached from.
//
// ⚠ IT IS NO LONGER THE ONLY HREF ON THE SURFACE. `scopeHref` and `entryHref` build
// same-origin browse links, and `scopeLink`'s comment says why neither goes through
// `safeHref`: that function ALLOWLISTS absolute http(s) and would refuse a relative path.
// The distinction that matters is the SOURCE of the URL, not its position — a task ref is
// a whole URL out of a store file, and these are constant paths with encoded operands.
//
// 🔴 A REF THAT DOES NOT PASS RENDERS AS TEXT RATHER THAN AS A DEAD LINK OR AS
// NOTHING. Dropping it would hide a fact the file carries; rendering `<a href="">`
// would put a clickable element on the page whose target the reader cannot see.
// Plain text is visible, inert, and says what the file says.
//
// 🔴 WHAT REACHES `safeHref` IS THE REGISTRY'S RESOLVED URL, AND THE LINK TEXT IS STILL THE
// REF THE FILE CARRIES. Before the registry existed the RAW ref was handed to `safeHref`,
// which allowlists http(s) — so `github:owner/repo#428` matched no permitted scheme and EVERY
// external reference on this surface rendered as `class="task refused"`. That was the measured
// state of #428's criterion 4, and it is what this function changes.
//
// 🔴 A REF THE REGISTRY RESOLVED TO NOTHING STILL GOES THROUGH `safeHref` — it is not
// short-circuited to the refused branch. That looks redundant, since `safeHref("")` is false,
// and it is deliberate: ONE path to the href means there is no second branch for a future edit
// to forget, and the empty string is exactly the input `safeHref`'s own first test rejects.
//
// ⚠ THE REF'S OWN TEXT IS NO LONGER A URL CANDIDATE, AND THAT IS A NARROWING. A store file
// carrying `refs: [javascript:alert(1)]` used to reach `safeHref` as that string; now it
// reaches the registry, which has no `javascript` template and answers no URL. The
// scheme-shaped ref is therefore refused twice over — but `safeHref` is still the guard,
// because the OPERATOR-supplied base for a self-hosted system reaches it unfiltered.
func taskItem(ref EntryRef) g.Node {
	href, ok := safeHref(ref.URL)
	if !ok {
		return h.Li(h.Class("task refused"), g.Text(ref.Raw))
	}
	return h.Li(h.Class("task"), h.A(h.Href(href), g.Text(ref.Raw)))
}

// safeHref is the ONE place a URL reaches an href attribute, and it ALLOWLISTS.
//
// 🔴 A DENYLIST IS THE WRONG SHAPE HERE AND THAT IS NOT A STYLE PREFERENCE. The
// set of URL schemes a browser will execute is open — `javascript:`, `data:`,
// `vbscript:`, and whatever a handler registers — so a list of the ones to refuse
// is a list that is wrong the moment it is written. Two schemes are permitted, and
// a third requires an edit here.
//
// 🔴 THE SCHEME TEST IS CASE-INSENSITIVE AND WHITESPACE-STRIPPED BECAUSE BROWSERS
// ARE — AND WITH AN ALLOWLIST THAT PROTECTS THE *PERMIT* SIDE, WHICH IS THE OPPOSITE
// OF WHAT IT WOULD DO IN A DENYLIST. Measured, not reasoned: removing the
// `ToLower` makes `HTTPS://tracker.invalid/…` be REFUSED and changes nothing about
// `JaVaScRiPt:` — which an allowlist rejects at any casing, because it matches no
// permitted prefix however it is spelled. The same for the strip: removing it
// refuses `  https://…`. So neither is what stops the script-scheme attack; the
// allowlist is. What they buy is two real things: a correctly-spelled URL is not
// silently demoted to plain text, and the value written into the href is the
// STRIPPED one, so what the page shows and what the browser resolves are the same
// string. RFC 3986 §3.1 makes a scheme case-insensitive, and the HTML specification
// strips leading and trailing ASCII whitespace — including C0 controls — from a URL
// attribute before resolving it.
//
// ⚠ WHAT THIS DOES NOT CLAIM: it is not a URL validator. A permitted `https://`
// target may still be hostile — it may be a tracking pixel or a phishing page —
// and nothing here says otherwise. What it claims is narrower and is the property
// the escaper cannot supply: no value leaving this function can cause the BROWSER
// to execute the page author's string as code.
func safeHref(raw string) (string, bool) {
	// The HTML URL-attribute strip: ASCII whitespace and C0 controls at both ends.
	trimmed := strings.Trim(raw, "\x00\x01\x02\x03\x04\x05\x06\x07\x08\t\n\v\f\r\x0e\x0f"+
		"\x10\x11\x12\x13\x14\x15\x16\x17\x18\x19\x1a\x1b\x1c\x1d\x1e\x1f \x7f")
	if trimmed == "" {
		return "", false
	}
	lower := strings.ToLower(trimmed)
	for _, scheme := range allowedSchemes {
		if strings.HasPrefix(lower, scheme) {
			return trimmed, true
		}
	}
	return "", false
}

// allowedSchemes is the whole allowlist. Lowercase, with the separator included so
// that a host literally named `https` cannot pass as a scheme.
//
// 🔴 A RELATIVE URL IS NOT ON THIS LIST, DELIBERATELY. A ref beginning `/` would be
// a same-origin path, which sounds safe and is the shape that lets a store entry
// address any route this binary serves — including ones a later phase adds. The UI
// builds its own internal links from the ledger, never from user text.
var allowedSchemes = []string{"http://", "https://"}
