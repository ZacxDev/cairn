// 🔴 IT BUILDS ITS OWN FRAME, FOR EXACTLY `SignInPage`'s REASON, AND ROUTING IT THROUGH
// `shell` IS THE NEXT PLAUSIBLE MISTAKE HERE TOO. There is no viewer, no session and no
