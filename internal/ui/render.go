// 🔴 EVERY CLASS NAME THIS FILE RENDERS IS A SEMANTIC NAME DEFINED IN `tailwind.css`, AND
// A RAW TAILWIND UTILITY HERE WOULD SIMPLY NOT WORK. The generator scans NOTHING — the
// stylesheet is compiled from `tailwind.css` alone — so `h.Class("flex gap-2")` would
// render a class the stylesheet has no rule for. `TestEveryRenderedClassHasARuleInTheStylesheet`
// is what catches that and is the ONLY thing that can: regenerating leaves `app.css`
// byte-identical, so the currency check stays green, and before that test existed the whole
// package did too.
//
// ⚠ AN EARLIER DRAFT DID CARRY RAW UTILITIES HERE, BEHIND AN `@source "./*.go"`, AND THAT
// SCAN WAS THE DEFECT. Tailwind's extractor reads the whole file including COMMENTS, and
// this package's comments are dense by house rule: six utilities were generated into
// `app.css` out of ordinary English (`table`, `visible`, `fixed`, `static`, `hidden`,
// `sticky`) with no `Class()` literal anywhere, and rewording one comment line changed the
// generated bytes — turning a build gate red on a comment-only commit with a message that
// blamed a hand-edit. `tailwind.css`'s own header records the measurement.

// PageView is everything the three BROWSE pages render, assembled by the handler.
//
// 🔴 ONE TYPE FOR THREE PAGES, FOR THE REASON `ShareView` IS ONE TYPE FOR TWO. Each of
// these pages carries the same shell — viewer, sign-out control, breadcrumbs back to the
// root — and every one of them is reached through a handler that has already called
// [Source.Visible]. Three structs would be three places to forget the shell, and the
// breadcrumb trail would be the thing forgotten, because it is the only part that is
// invisible when it is missing rather than wrong.
//
// 🔴 PRECONDITION: `Scopes` IS THE RESULT OF AN AUTHORITY QUERY, EVEN WHEN IT IS EMPTY.
// The empty branch below renders a sentence that distinguishes "your credential may see
// nothing" from "the store is empty", and it can only say that if somebody asked.
// Handing this a `nil` slice without calling [Source.Visible] makes it assert an answer
// nobody obtained — which a route on this server once did.
// `TestEveryContentRouteConsultsTheAuthority` pins that every route in the table ASKS,
// across the whole dispatch table rather than at the one call site. It does NOT pin that
// the answer is what reaches this function — a handler that called [Source.Visible] and
// then passed `nil` anyway would satisfy it.
type PageView struct {
	// Viewer is the signed-in principal's display name. USER TEXT.
	Viewer string
	// CSRF is the token from [csrfTokenFor] — empty for a caller with no session
	// cookie, in which case the sign-out control is not rendered at all. A button that
	// is present and cannot work is worse than one that is absent: it teaches a user
	// that sign-out is unreliable.
	CSRF string
	// Scopes is the WHOLE narrowed answer, on every page. The root renders it as cards;
	// the other two pages pick out of it and still carry it, because the breadcrumb and
	// the navigation page are built from it.
	Scopes []Scope

	// Query is the search box's current value, "" when nothing was asked. USER TEXT,
	// reflected into a form control — see `handlePage` for why that position is
	// different from a reflected banner.
	Query string
	// Results is the answer to Query, nil when there was no query. A non-nil Results
	// with no Hits is a real zero and renders as one; nil means nobody asked.
	Results *SearchResults

	// Scope is the scope under view on the scope and entry pages, nil on the root.
	Scope *Scope
	// Entry is the entry under view on the entry page, nil elsewhere.
	Entry *Entry
}

// Page is the ROOT: every scope this credential may read, as cards, plus the search box.
//
// 🔴 EVERY USER STRING GOES THROUGH `g.Text` OR THROUGH A QUOTED ATTRIBUTE VALUE,
// AND NOTHING GOES THROUGH `g.Raw`. See this package's doc comment for the measured
// scope of gomponents' escaper and for the one place it is NOT enough.
func Page(v PageView) g.Node {
	return shell("cairn", v, nil,
		searchForm(v),
		// 🔴 `g.Iff` AND NOT `g.If`, AND THE DIFFERENCE IS A NIL DEREFERENCE RATHER THAN
		// A STYLE CHOICE. `g.If(cond, node)` takes a NODE, so Go evaluates the argument
		// before the condition is ever consulted — `searchResults(v)` would run, and
		// dereference `v.Results`, on every page load that carried no query. Measured as a
		// segfault in the route walk, not reasoned about. `g.Iff` takes a closure and
		// calls it only when the condition holds. Every `g.If` below is safe because its
		// argument dereferences nothing; any new one that reads a pointer must be `g.Iff`.
		g.Iff(v.Results != nil, func() g.Node { return searchResults(v) }),
		// 🔴 THE CARDS ARE WITHHELD WHILE A QUERY IS IN FORCE, AND THE ALTERNATIVE WAS
		// MEASURED WORSE ON ITS OWN TERMS RATHER THAN ON TASTE. Rendering both puts a
		// full, unfiltered scope list directly under a result list, and the two read as
		// one list: the second half then looks like more results that happen to match
		// nothing. The way back is a link that says so, not a second list nobody asked
		// for.
		g.If(v.Results == nil, g.Group([]g.Node{
			g.If(len(v.Scopes) == 0, h.P(h.Class("empty"), g.Text(
				"No scope is visible to this credential. That is an authority "+
					"answer, not an empty store."))),
			g.If(len(v.Scopes) > 0, h.Div(h.Class("scope-grid"), g.Map(v.Scopes, scopeCard))),
			g.If(len(v.Scopes) > 0, rootLegend()),
		})),
	)
}

// NavigatePage is what `/scope` and `/entry` answer when the request NAMED NOTHING.
//
// 🔴 IT IS A 200 AND NOT A REFUSAL, AND THE DISCRIMINATOR IS WHETHER THE CALLER NAMED
// SOMETHING. A refusal on this surface is uniform because distinguishing "no such scope"
// from "not yours" would enumerate the store — but a request carrying no id at all has
// asked about no scope, so there is nothing for a uniform refusal to protect and nothing
// the answer can leak. What it gets instead is the thing a person who landed here wants:
// the list of scopes they can reach, which is also the breadcrumb parent of both pages.
//
// ⚠ IT IS DELIBERATELY NOT THE ROOT PAGE. Two rows rendering one page is the shape
// `routes` deleted `GET /entries` for. This is a short list of links with no cards, no
// counts and no search box — a navigation answer, not a second copy of the root.
func NavigatePage(v PageView) g.Node {
	return shell("cairn", v, nil,
		h.Section(
			h.Class("card"),
			h.H2(g.Text("Pick a scope")),
			h.P(h.Class("note"), g.Text(
				"This address names no scope, so there is nothing to show yet. "+
					"These are the scopes this credential can read.")),
			g.If(len(v.Scopes) == 0, h.P(h.Class("empty"), g.Text(
				"No scope is visible to this credential. That is an authority "+
					"answer, not an empty store."))),
			g.If(len(v.Scopes) > 0, h.Ul(h.Class("scope-links"), g.Map(v.Scopes, func(s Scope) g.Node {
				return h.Li(scopeLink(s))
			}))),
		),
	)
}

// ScopePage is ONE scope's entry list.
func ScopePage(v PageView) g.Node {
	s := *v.Scope
	return shell("cairn — "+s.Name, v, []crumb{{Label: s.Name}},
		h.Section(
			h.Class("card"),
			h.H2(g.Text(s.Name)),
			h.P(h.Class("card-what"), g.Text(scopeWhat)),
			scopeStats(s),
			g.If(len(s.Entries) == 0, h.P(h.Class("empty"), g.Text(
				"This scope holds no readable entry. That is what the index says about "+
					"this scope, not what your credential is allowed to see: a scope you "+
					"could not read would not be addressable from here at all."))),
			g.If(len(s.Entries) > 0, h.Ul(h.Class("entry-list"), g.Map(s.Entries, func(e Entry) g.Node {
				return entryRow(s, e)
			}))),
			malformedBlock(s),
		),
		scopeLegend(),
	)
}

// EntryPage is ONE entry: the sections its file carries and the line items under the
// journal heading.
//
// 🔴 THIS IS THE ENTRY-CONTENT PATH THE RAW-NODE BAN NAMES, AND IT IS THE WIDEST ONE ON
// THIS SURFACE. Until this page existed an entry's BODY never reached a browser at all —
// only its ref, title, aliases and task refs did. Every string below came out of a
// markdown file somebody else wrote, in both text and attribute positions, and
// `entryRow`'s comment records why the two contexts have to be exercised separately.
func EntryPage(v PageView) g.Node {
	s, e := *v.Scope, *v.Entry
	return shell("cairn — "+e.Ref, v,
		[]crumb{{Label: s.Name, Href: scopeHref(s)}, {Label: e.Ref}},
		h.Section(
			h.Class("card"),
			h.H2(g.Text(e.Ref)),
			h.P(h.Class("card-what"), g.Text(entryWhat)),
			provenance(s, e),
			entryCounts(e),
			g.If(len(e.Aliases) > 0, labelledList("Aliases", "the `aliases:` front-matter key, as written",
				h.Ul(h.Class("aliases"), g.Map(e.Aliases, plainItem)))),
			g.If(len(e.Tasks) > 0, labelledList("Tasks", "the `tasks:` front-matter key, as written",
				h.Ul(h.Class("tasks"), g.Map(e.Tasks, taskItem)))),
			g.If(len(e.Sections) == 0, h.P(h.Class("empty"), g.Text(
				"This entry carries none of the headings a reader surfaces. The file exists "+
					"and the loader accepted it; it simply has no `## What it is`, "+
					"`## Pointers` or `## Nuance / work-history` section in it."))),
			g.Map(e.Sections, sectionBlock),
			missingBlock(e),
		),
		entryLegend(),
	)
}

// crumb is one step of the breadcrumb trail. An empty `Href` is the CURRENT page, which
// renders as text rather than as a link to itself.
type crumb struct {
	Label string
	Href  string
}

// shell is the one page frame, so three pages cannot end up with three headers.
//
// 🔴 THE BREADCRUMB IS PART OF THE FRAME RATHER THAN PER PAGE, BECAUSE A MISSING WAY BACK
// IS INVISIBLE. Two levels of drill-down with no trail is the standard failure of this
// information architecture: every page looks complete, and the only symptom is a reader
// reaching for the browser's back button on a surface that could have told them where
// they were. Putting it here means a page added later gets it without anybody remembering.
func shell(title string, v PageView, crumbs []crumb, body ...g.Node) g.Node {
	return c.HTML5(c.HTML5Props{
		Title:    title,
		Language: "en",
		// ⚠ NO `<meta name="viewport">` IS SPELLED HERE, AND THAT IS A MEASUREMENT RATHER
		// THAN AN OMISSION. Without one a phone lays the page out at ~980 CSS pixels and
		// scales it down, so every responsive rule in `tailwind.css` would apply at a width
		// no reader has — `uiaudit` reports `missing_viewport_meta` for exactly that, and
		// treats it as the reason a narrow capture's `innerWidth` may legitimately exceed
		// the emulated width. `c.HTML5` ALREADY EMITS IT: read out of gomponents v1.3.0's
		// `components/components.go`, which unconditionally puts
		// `<meta name="viewport" content="width=device-width, initial-scale=1">` in the
		// head. A draft of this function added a second identical tag; the walk reported
		// `no-viewport-meta=false` either way, which is how a duplicate would have shipped
		// unnoticed. If gomponents ever drops it, this is the function to spell it in.
		Head: []g.Node{stylesheetLink()},
		Body: []g.Node{
			h.Header(
				h.Class("page-header"),
				// The wordmark is a link to the root on every page, which is the one
				// navigation affordance a reader tries before they read anything.
				h.H1(h.A(h.Href(RootPath), g.Text("cairn"))),
				// The viewer's display name is USER TEXT: it comes from a
				// `control.Principal`, which comes from a provisioned user record.
				h.P(h.Class("viewer"), g.Text("signed in as "+v.Viewer)),
				g.If(v.CSRF != "", signOutForm(v.CSRF)),
			),
			g.If(len(crumbs) > 0, breadcrumbs(crumbs)),
			h.Main(h.Class("page-main"), g.Group(body)),
		},
	})
}

func breadcrumbs(crumbs []crumb) g.Node {
	return h.Nav(
		h.Class("crumbs"),
		// The trail always starts at the root, so the first step is spelled here rather
		// than by every caller.
		h.A(h.Class("crumb"), h.Href(RootPath), g.Text("All scopes")),
		g.Map(crumbs, func(c crumb) g.Node {
			if c.Href == "" {
				return h.Span(h.Class("crumb crumb-here"), g.Text(c.Label))
			}
			return h.A(h.Class("crumb"), h.Href(c.Href), g.Text(c.Label))
		}),
	)
}

// searchForm is a plain `GET` form, and the absence of script is the point.
//
// 🔴 NO JAVASCRIPT, ON A SURFACE WHOSE XSS STORY PARTLY RESTS ON THERE BEING NONE. A
// type-ahead would need a script, a script would need a fetch, and `document.scripts.length`
// would stop being zero — which is a property `uiaudit` measures on every captured page
// precisely so that it cannot drift silently. A `GET` form gives a shareable URL, a working
// back button and a browser-native reload for free, none of which a script version gets
// without writing them.
//
// ⚠ THE ACTION IS THE ROOT PATH, WHICH IS ALSO WHERE A BLANK SUBMISSION LANDS. Submitting an
// empty box is how a reader clears a search, and it arrives as `?q=` — which
// `handlePage` trims to "" and treats as no query at all.
func searchForm(v PageView) g.Node {
	return h.FormEl(
		h.Class("searchbar"),
		h.Method("get"),
		h.Action(RootPath),
		h.Label(h.For("q"), g.Text("Search entries")),
		h.Input(
			h.ID("q"),
			// `search` rather than `text`: a browser renders a clear affordance and an
			// on-screen keyboard offers a search key. Both are free and neither needs a
			// script.
			h.Type("search"),
			h.Name(QueryQuery),
			h.Value(v.Query),
			h.Placeholder("words to look for"),
			h.AutoComplete("off"),
		),
		h.Button(h.Type("submit"), g.Text("Search")),
	)
}

// searchResults renders the scored answer from `internal/report`.
//
// 🔴 A ZERO IS RENDERED AS A READABLE ZERO, WHICH IS `report.SearchReport.BestBelow`'s
// WHOLE REASON FOR EXISTING. "Nothing matched" and "the best candidate fell just under the
// threshold" are different facts with different next actions, and a page that prints one
// blank for both has diagnosed nothing. The searched-scope list is rendered beside it for
// the same reason one level up: a zero over an EMPTY scope set is an authority answer, not
// a statement about the store.
func searchResults(v PageView) g.Node {
	r := *v.Results
	return h.Section(
		h.Class("card results"),
		h.H2(g.Text("Search")),
		h.P(h.Class("card-what"), g.Text(searchWhat)),
		h.P(h.Class("note"), g.Text(searchSummary(r))),
		h.P(h.Class("note"), g.Text("Searched: "+scopeListText(r.ScopesSearched))),
		h.P(h.Class("note"), h.A(h.Href(RootPath), g.Text("Clear the search and show every scope"))),
		g.If(len(r.Hits) == 0 && r.BestBelow != "", h.P(h.Class("empty"), g.Text(
			"Nothing cleared the threshold. The closest entry was `"+r.BestBelow+"` — "+
				"so this is a near miss rather than a store with nothing in it."))),
		g.If(len(r.Hits) == 0 && r.BestBelow == "", h.P(h.Class("empty"), g.Text(
			"Nothing matched, and nothing came close either: no entry in the scopes above "+
				"scored against these words at all."))),
		g.If(len(r.Hits) > 0, h.Ul(h.Class("hits"), g.Map(r.Hits, hitItem))),
	)
}

func hitItem(hit Hit) g.Node {
	return h.Li(
		h.Class("hit"),
		h.P(
			h.Class("hit-where"),
			// The hit LINKS to the entry it came from, which is the whole reason the
			// scope id is carried onto the hunk. A hit that a reader cannot open is a
			// search result they have to go and find by hand.
			entryLinkFor(hit.ScopeID, hit.Ref, hit.Ref),
			h.Span(h.Class("hit-scope"), g.Text(hit.Scope)),
			g.If(hit.Section != "", h.Span(h.Class("hit-section"), g.Text(hit.Section))),
			h.Span(h.Class("hit-score"), g.Text(formatScore(hit.Score))),
			// `entry-name` means the entry's REF or an alias matched and no line did, so
			// the lines below are the entry's best block shown as a worked example rather
			// than the thing that matched. Without it a name-only hit is indistinguishable
			// from a line hit.
			g.If(hit.Basis == report.BasisEntryName,
				h.Span(h.Class("badge badge-quiet"), g.Text("matched the entry name"))),
		),
		h.Pre(h.Class("hit-lines"), h.Code(g.Text(strings.Join(hit.Lines, "\n")))),
	)
}

// scopeCard is ONE scope, as the root page's card.
//
// 🔴 EVERY FIELD ON IT IS LABELLED WITH WHAT IT IS IN THE UNDERLYING STORE, AND THAT IS
// THE WHOLE POINT OF THE CARD RATHER THAN A FLOURISH. The first version of this page
// rendered a bare heading over a list of refs, and the operator's complaint about it was
// exactly that nothing said what the heading WAS or what the list items were. A card
// whose title is unexplained is a card a reader has to guess at, and they will guess it
// is a project, or a file, or a tag.
func scopeCard(s Scope) g.Node {
	return h.Section(
		h.Class("card"),
		h.Div(
			h.Class("card-head"),
			h.H2(scopeLink(s)),
			h.Span(h.Class("kind"), g.Text("scope")),
		),
		h.P(h.Class("card-what"), g.Text(scopeWhat)),
		scopeStats(s),
		g.If(len(s.Entries) > 0, h.Ul(
			h.Class("card-entries"),
			g.Map(cardEntryPreview(s.Entries), func(e Entry) g.Node {
				return h.Li(h.Class("card-entry"), h.Span(h.Class("ref"), g.Text(e.Ref)))
			}),
		)),
		g.If(len(s.Entries) > cardPreview, h.P(h.Class("card-more"), g.Text(
			plural(len(s.Entries)-cardPreview, "more entry", "more entries")+" not shown"))),
		g.If(len(s.Entries) == 0, h.P(h.Class("empty"), g.Text("No readable entry in this scope."))),
		g.If(len(s.Malformed) > 0, h.P(h.Class("card-warn"), g.Text(
			plural(len(s.Malformed), "entry file", "entry files")+" in this scope could not be read"))),
	)
}

// cardPreview is how many entry refs a card lists before it says how many it left out.
//
// ⚠ A FIXED NUMBER, AND THE CARD SAYS WHEN IT TRUNCATED. A card that silently showed the
// first few would read as a complete list of a small scope.
const cardPreview = 5

func cardEntryPreview(entries []Entry) []Entry {
	if len(entries) > cardPreview {
		return entries[:cardPreview]
	}
	return entries
}

// scopeStats is the card's counts, and each one names what it counted.
//
// 🔴 `declared open` RATHER THAN `open`, AND THE WORD IS LOAD-BEARING. The openness
// marker is opt-in: `report.RecalledEntry.OpenCount`'s own comment records that a zero
// means "nothing was declared" and NOT "nothing is open", and every bullet written before
// the marker existed carries none. A badge reading `0 open` over a scope full of
// unfinished work would be a completeness claim this store cannot make.
func scopeStats(s Scope) g.Node {
	return h.P(
		h.Class("card-stats"),
		h.Span(h.Class("stat"), g.Text(plural(len(s.Entries), "entry", "entries"))),
		g.If(s.OpenCount() > 0, h.Span(h.Class("stat stat-open"),
			g.Text(plural(s.OpenCount(), "bullet", "bullets")+" declared open"))),
		g.If(s.OpenCount() == 0, h.Span(h.Class("stat stat-quiet"),
			g.Text("no bullet declares itself open"))),
		g.If(len(s.Malformed) > 0, h.Span(h.Class("stat stat-warn"),
			g.Text(plural(len(s.Malformed), "unreadable file", "unreadable files")))),
	)
}

// entryRow is one entry on the scope page.
func entryRow(s Scope, e Entry) g.Node {
	return h.Li(
		h.Class("entry-row"),
		// 🔴 THE REF IS IN AN ATTRIBUTE VALUE *AND* IN TEXT CONTENT, DELIBERATELY. The
		// two contexts escape through different code in gomponents — `valueAttr` for the
		// first, `Text` for the second — so a page that put user text in only one of them
		// would leave the other's escaping untested here. A `title` attribute is the
		// honest use as well: the ref is often wider than the column. Here it reaches a
		// THIRD position on top of those two — a query parameter inside an href — which
		// `entryHref` percent-encodes rather than escapes.
		h.Span(h.Class("ref"), h.TitleAttr(e.Ref), entryLinkFor(s.ID, e.Ref, e.Ref)),
		h.Span(h.Class("title"), g.Text(e.Title)),
		g.If(e.OpenCount > 0, h.Span(h.Class("badge badge-open"),
			g.Text(plural(e.OpenCount, "OPEN bullet", "OPEN bullets")))),
		g.If(e.NearMissCount > 0, h.Span(h.Class("badge badge-near"),
			g.Text(plural(e.NearMissCount, "near-miss marker", "near-miss markers")))),
		h.Span(h.Class("entry-count"), g.Text(plural(e.BulletCount, "journal bullet", "journal bullets"))),
		g.If(len(e.Aliases) > 0, h.Ul(
			h.Class("aliases"),
			g.Map(e.Aliases, func(a string) g.Node { return h.Li(g.Text(a)) }),
		)),
		g.If(len(e.Tasks) > 0, h.Ul(h.Class("tasks"), g.Map(e.Tasks, taskItem))),
	)
}

// provenance is the entry page's "where did this come from" block.
//
// ⚠ IT NAMES A FILENAME AND A SCOPE, WHICH ARE NOT DEPLOYMENT FACTS. The scope is a name
// the caller already proved they may read and the filename is relative to it; neither is
// a filesystem PATH, and the store root is deliberately not on the page — a path is a
// fact about the deployment rather than about the request, which is the rule
// `handlePage`'s error branch follows.
func provenance(s Scope, e Entry) g.Node {
	return h.Dl(
		h.Class("provenance"),
		h.Dt(h.Class("prov-key"), g.Text("scope")),
		h.Dd(h.Class("prov-val"), g.Text(s.Name)),
		h.Dt(h.Class("prov-key"), g.Text("file")),
		h.Dd(h.Class("prov-val"), g.Text(e.Filename)),
		h.Dt(h.Class("prov-key"), g.Text("service:")),
		h.Dd(h.Class("prov-val"), g.Text(e.Title)),
	)
}

func entryCounts(e Entry) g.Node {
	return h.P(
		h.Class("card-stats"),
		h.Span(h.Class("stat"), g.Text(plural(e.BulletCount, "journal bullet", "journal bullets"))),
		g.If(e.OpenCount > 0, h.Span(h.Class("stat stat-open"),
			g.Text(plural(e.OpenCount, "declared open", "declared open")))),
		g.If(e.NearMissCount > 0, h.Span(h.Class("stat stat-warn"),
			g.Text(plural(e.NearMissCount, "near-miss marker", "near-miss markers")))),
	)
}

// sectionBlock is ONE `##` heading of the file and what sits under it.
//
// 🔴 THE JOURNAL SECTION RENDERS AS LINE ITEMS AND EVERY OTHER SECTION RENDERS AS TEXT,
// AND NEITHER IS MARKDOWN. There is no markdown renderer on this surface and adding one
// would be a second parser to disagree with `internal/store` — plus a new sink for
// attacker-authored markup, which is the one thing this package's whole escaping story is
// built around. A `<pre>` shows the file's own bytes: what the writer typed, wrapped the
// way they wrapped it, with no interpretation to get wrong.
func sectionBlock(s Section) g.Node {
	return h.Section(
		h.Class("entry-section"),
		h.H3(h.Class("section-head"), g.Text(s.Heading)),
		g.If(len(s.Bullets) == 0 && s.Body == "", h.P(h.Class("empty"), g.Text(
			"Present and empty. The heading is in the file with nothing under it, which "+
				"is a different fact from the heading being absent."))),
		g.If(len(s.Bullets) == 0 && s.Body != "", h.Pre(h.Class("section-body"), h.Code(g.Text(s.Body)))),
		g.If(len(s.Bullets) > 0, h.Ul(h.Class("bullets"), g.Map(s.Bullets, bulletItem))),
	)
}

// bulletItem is ONE line item.
//
// 🔴 THE BADGE IS DERIVED FROM `store.JournalBullet.OpennessPopulation` AND NEVER FROM A
// SUBSTRING OF THE TEXT, WHICH IS WHAT KEEPS A REAL MARKER DISTINGUISHABLE FROM ONE THAT
// MERELY LOOKS LIKE ONE. A guard — or a renderer — keyed on the WORD `OPEN` is walkable
// by anybody who writes `OPEN` in prose, and it would also miss the case that matters
// most: `store.PopulationNearMiss` is a bullet that TRIED to write a marker and missed
// the grammar, and `report.RecalledEntry.NearMissCount`'s comment records that until it
// was counted separately it was byte-identical to "no marker" on the read surface — the
// badge simply did not render, and a vanishing badge looks like success. So a near miss
// gets its OWN badge, with its own words, and never the open one.
func bulletItem(b Bullet) g.Node {
	return h.Li(
		h.Class("bullet"),
		h.P(
			h.Class("bullet-meta"),
			g.If(b.Date != "", h.Span(h.Class("bullet-date"), g.Text(b.Date))),
			g.If(b.Population == store.PopulationOpen,
				h.Span(h.Class("badge badge-open"), g.Text("OPEN"))),
			g.If(b.Population == store.PopulationNearMiss,
				h.Span(h.Class("badge badge-near"), g.Text("near-miss marker"))),
			g.If(b.Population == store.PopulationResolved,
				h.Span(h.Class("badge badge-quiet"), g.Text("resolved"))),
			g.If(b.Population == store.PopulationUnverifiable,
				h.Span(h.Class("badge badge-near"), g.Text("resolved, no sha"))),
		),
		h.Pre(h.Class("bullet-body"), h.Code(g.Text(b.Text()))),
	)
}

// malformedBlock renders the entry files the loader REFUSED.
//
// 🔴 A BROWSER THAT DROPPED THEM WOULD DISAGREE WITH THE CLI WHILE LOOKING COMPLETE, and
