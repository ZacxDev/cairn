// scopeLink and entryLinkFor are the ONLY places an internal browse URL is built.
//
// 🔴 THE PATHS ARE CONSTANTS AND THE OPERANDS GO THROUGH `url.Values.Encode`, WHICH IS
// THE HALF `shareIndex` DOES NOT NEED. A scope id is minted by `control.NewID`/
// `control.DerivedID` over an alphabet chosen to be safe in a URL without quoting, so the
// share flow concatenates it directly. An entry REF is not: it is a filename stem out of
// a file somebody else wrote, so it can carry `&`, `#`, a space or a percent sequence, and
// concatenating it would let the file's own name inject a second query parameter.
// `Encode` is the encoder for that position, and it sorts its keys, so the URL a page
// renders for one entry is the same string every time.
//
// ⚠ `safeHref` IS NOT REACHED AND MUST NOT BE, which is `shareIndex`'s ruling for the same
// shape: it ALLOWLISTS absolute http(s), and these are same-origin paths.
func scopeHref(s Scope) string {
	return ScopePath + "?" + url.Values{QueryID: []string{string(s.ID)}}.Encode()
}

func entryHref(scope control.ID, ref string) string {
	return EntryPath + "?" + url.Values{
		QueryScope: []string{string(scope)},
		QueryRef:   []string{ref},
	}.Encode()
}

// scopeLink renders a scope's name as a link, or as plain text when the authority named
// no id for it.
//
// 🔴 AN UNLINKED CARD RATHER THAN A LINK TO `?id=`, AND THE DIFFERENCE IS NOT COSMETIC. A
// scope with no id cannot be addressed, so a link would resolve to `/scope?id=` — which
// `handleScopePage` reads as "named nothing" and answers with the navigation page. A
// reader would click a scope and land on a list of scopes, which reads as a broken link
// rather than as the honest "this one has no address". `pickScope` refuses an empty id for
// the same reason from the other side.
func scopeLink(s Scope) g.Node {
	if s.ID == "" {
		return h.Span(h.Class("card-name"), g.Text(s.Name))
	}
	return h.A(h.Class("card-name"), h.Href(scopeHref(s)), g.Text(s.Name))
}

func entryLinkFor(scope control.ID, ref, label string) g.Node {
	if scope == "" || ref == "" {
		return h.Span(g.Text(label))
	}
	return h.A(h.Href(entryHref(scope, ref)), g.Text(label))
}

// searchSummary is the one sentence that says how much of the answer is on the page.
//
// 🔴 THE TRUNCATION IS STATED. A list that silently stopped at `report.DefaultMaxHits`
// reads as "that is all there is", which is the same defect as a scope card that showed
// the first five refs without saying so.
func searchSummary(r SearchResults) string {
	switch {
	case r.TotalHits == 0:
		return "No match cleared the threshold."
	case r.Omitted > 0:
		return plural(len(r.Hits), "match", "matches") + " shown of " +
			strconv.Itoa(r.TotalHits) + " that cleared the threshold; " +
			strconv.Itoa(r.Omitted) + " not shown."
	default:
		return plural(r.TotalHits, "match", "matches") + " cleared the threshold."
	}
}

// scopeListText renders the searched-scope set, and says so when it is EMPTY rather than
// printing nothing — an empty set is an authority answer.
func scopeListText(scopes []string) string {
	if len(scopes) == 0 {
		return "no scope at all, because this credential can read none. That is an " +
			"authority answer, not an empty store."
	}
	return strings.Join(scopes, ", ")
}

// formatScore renders a hunk score at the precision `internal/report` rounds to.
func formatScore(score float64) string {
	return strconv.FormatFloat(score, 'f', 2, 64)
}

// plural is the one place a count meets its noun, so the pages cannot disagree about
// whether one entry is "1 entries".
func plural(n int, one, many string) string {
	if n == 1 {
		return strconv.Itoa(n) + " " + one
	}
	return strconv.Itoa(n) + " " + many
}

// stylesheetLink is the ONE way a page reaches the stylesheet, so all three pages cannot
// end up under different rules.
//
// 🔴 A LINK RATHER THAN AN INLINE `<style>`, AND THE REASON IS NO LONGER THE POLICY THAT
// FIRST FORCED IT. This surface sent `style-src 'self'`, which forbids an inline style
// element in a conforming browser; that header is DELETED (see `writeHTML`), so the
// constraint is gone and the link is a choice. It is kept for two reasons that outlive the
// header: the bytes are now GENERATED by a Tailwind build (see `stylesheet.go`), and
// inlining 28 KB of them into every response would cost that on every page load where the
// route is cached instead; and `TestTheStylesheetIsServedAsItsOwnRoute` pins the page's
// `href` against the route that answers it, which is a relationship an inline stylesheet has
// no way to state.
//
// 🔴 IT EMITS THE HASHED PATH, AND THAT IS WHAT LICENSES THE YEAR-LONG `immutable` ON THE
// RESPONSE. [StylesheetHashedPath] carries a digest of the bytes it serves, so a theme change
// is a different URL and a browser holding the previous one never asks for it again. Linking
// [StylesheetPath] here instead would be silent: every page would render, every style would
// apply on a cold cache, and a returning visitor would go on applying whatever their cache
// holds for an unversioned URL — which is the failure `stylesheet.go` records.
// `TestNoPageLinksTheUnversionedStylesheetPath` refuses that edit.
//
// ⚠ THE HREF IS A PACKAGE VARIABLE NOW RATHER THAN A CONSTANT, AND IT IS STILL NEVER USER
// TEXT — it is derived at init from bytes that reach the binary through a `//go:embed` and
// from nothing else, so `safeHref` is not reached and must not be, for the reason `shareIndex`
// records about the same-origin case.
func stylesheetLink() g.Node {
	return h.Link(h.Rel("stylesheet"), h.Href(StylesheetHashedPath))
}

// signOutForm is a POST, and that is the security property rather than a style choice.
//
// 🔴 A SIGN-OUT LINK WOULD BE A `GET`, AND GATE (6) DOES NOT GUARD `GET`. A state change
// behind a safe method is reachable by any `<img src>` on any page in the world; the
// victim's browser fetches it, the cookie rides along, and they are signed out. Worse,
// the same shape is how a link-prefetcher or an antivirus scanner performs the action by
// accident. `stateChanging` is what decides which requests are guarded, so a state change
